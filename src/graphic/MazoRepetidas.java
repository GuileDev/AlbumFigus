    private void construirMazo() {
        Color fondoPanel = oscuro ? new Color(30, 30, 36) : new Color(245, 245, 245);

        JPanel gridPanel = new JPanel(new GridLayout(0, 4, 20, 20));
        gridPanel.setBackground(fondoPanel);
        gridPanel.setBorder(BorderFactory.createEmptyBorder(25, 25, 25, 25));

        int extras = 0;

        if (album != null) {
            // Cuantas veces tiene el usuario cada figurita
            Map<Integer, Integer> conteo = new HashMap<>();
            for (int id : album.figuritas) {
                conteo.merge(id, 1, Integer::sum);
            }

            // Las cartas salen ordenadas por numero de figurita
            List<Figurita> catalogoOrdenado = new ArrayList<>(album.catalogo);
            catalogoOrdenado.sort((a, b) -> Integer.compare(a.getNumero(), b.getNumero()));

            for (Figurita f : catalogoOrdenado) {
                int cantidad = conteo.getOrDefault(f.getIdFigurita(), 0);
                int repetidas = Math.max(0, cantidad - 1);
                for (int i = 0; i < repetidas; i++) {
                    gridPanel.add(new CartaRepetida(f, oscuro));
                    extras++;
                }
            }
        }

        jScrollPane1.setViewportView(gridPanel);

        jLabelContador.setText(extras == 0
                ? "No tenes repetidas"
                : "Tenes " + extras + (extras == 1 ? " repetida" : " repetidas"));
        jLabelVacio.setVisible(extras == 0);
        jScrollPane1.setVisible(extras > 0);
    }

    private static class CartaRepetida extends JPanel {

        private static final int ANCHO = 210;
        private static final int ALTO = 290;

        CartaRepetida(Figurita figurita, boolean oscuro) {
            Color colorPastel;
            Color colorPastelClaro;
            Color colorTexto;
            Color colorTextoSuave;
            Color colorBorde;

            if (oscuro) {
                colorPastel = new Color(96, 106, 150);
                colorPastelClaro = new Color(74, 82, 122);
                colorTexto = new Color(240, 240, 250);
                colorTextoSuave = new Color(185, 190, 215);
                colorBorde = new Color(150, 160, 210);
            } else {
                int numero = figurita != null ? figurita.getNumero() : 0;
                java.util.Random random = new java.util.Random(numero * 131542391L);
                int r = 180 + random.nextInt(60);
                int g = 180 + random.nextInt(60);
                int b = 180 + random.nextInt(60);
                colorPastel = new Color(r, g, b);
                colorPastelClaro = new Color(Math.min(255, r + 40), Math.min(255, g + 40), Math.min(255, b + 40));
                colorTexto = Color.BLACK;
                colorTextoSuave = new Color(120, 120, 120);
                colorBorde = Color.BLACK;
            }

            setPreferredSize(new Dimension(ANCHO, ALTO));
            setMinimumSize(new Dimension(ANCHO, ALTO));
            setMaximumSize(new Dimension(ANCHO, ALTO));
            setBackground(colorPastelClaro);
            setBorder(BorderFactory.createLineBorder(colorBorde, 2));
            setLayout(null);

            String numeroTexto = figurita != null ? String.valueOf(figurita.getNumero()) : "?";
            String jugador = figurita != null ? figurita.getJugador() : "???";
            String posicion = figurita != null ? figurita.getPosicion() : "";
            String rareza = figurita != null ? figurita.getRareza() : "";
            String seleccion = (figurita != null && figurita.getSeleccion() != null) ? figurita.getSeleccion().getNombre() : "";

            JLabel numLabel = new JLabel("#" + numeroTexto);
            numLabel.setFont(new Font("Segoe UI", Font.BOLD, 20));
            numLabel.setHorizontalAlignment(SwingConstants.CENTER);
            numLabel.setForeground(colorTexto);
            numLabel.setBounds(0, 15, ANCHO, 30);
            add(numLabel);

            JLabel jugadorLabel = new JLabel("<html><center>" + jugador + "</center></html>");
            jugadorLabel.setFont(new Font("Segoe UI", Font.BOLD, 16));
            jugadorLabel.setHorizontalAlignment(SwingConstants.CENTER);
            jugadorLabel.setForeground(colorTexto);
            jugadorLabel.setBounds(5, 60, ANCHO - 10, 60);
            add(jugadorLabel);

            JLabel posicionLabel = new JLabel(posicion + (seleccion.isEmpty() ? "" : " - " + seleccion));
            posicionLabel.setFont(new Font("Segoe UI", Font.PLAIN, 12));
            posicionLabel.setHorizontalAlignment(SwingConstants.CENTER);
            posicionLabel.setForeground(colorTextoSuave);
            posicionLabel.setBounds(0, 125, ANCHO, 22);
            add(posicionLabel);

            JLabel rarezaLabel = new JLabel(rareza);
            rarezaLabel.setFont(new Font("Segoe UI", Font.ITALIC, 13));
            rarezaLabel.setHorizontalAlignment(SwingConstants.CENTER);
            rarezaLabel.setForeground(colorTextoSuave);
            rarezaLabel.setBounds(0, 220, ANCHO, 22);
            add(rarezaLabel);
        }
    }

