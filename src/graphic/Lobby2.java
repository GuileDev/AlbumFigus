    private class SlotPanel extends JPanel {
        private int numero;
        private boolean hover;
        private boolean seleccionado;
        private int animacionWidth;
        private int animacionHeight;
        private int animacionX;
        private int animacionY;
        private Timer hoverTimer;
        private Timer clickTimer;
        private JLabel numLabel;
        private JLabel vacioLabel;

        private static final int TAMAÑO_NORMAL_WIDTH = 210;
        private static final int TAMAÑO_NORMAL_HEIGHT = 290;
        private static final int TAMAÑO_EXPANDIDO_WIDTH = 240;
        private static final int TAMAÑO_EXPANDIDO_HEIGHT = 330;
        private static final int PASO_ANIMACION = 6;

        public SlotPanel(int numero) {
            this.numero = numero;
            this.hover = false;
            this.seleccionado = false;
            this.animacionWidth = TAMAÑO_NORMAL_WIDTH;
            this.animacionHeight = TAMAÑO_NORMAL_HEIGHT;
            this.animacionX = 0;
            this.animacionY = 0;

            initSlot();
            initAnimaciones();
        }


        /**
         * Aplica el aspecto oscuro o claro a esta casilla del álbum.
         */
        public void setModoOscuro(boolean oscuro, Color texto, Color textoClaro) {
            if (oscuro) {
                setBackground(new Color(50, 50, 50));
                setBorder(BorderFactory.createLineBorder(new Color(90, 90, 90), 2));
            } else {
                  setBorder(BorderFactory.createLineBorder(Color.BLACK, 2));
            }
            numLabel.setForeground(texto);
            vacioLabel.setForeground(textoClaro);
            revalidate();
            repaint();
        }

        private void initSlot() {
            setPreferredSize(new Dimension(TAMAÑO_NORMAL_WIDTH, TAMAÑO_NORMAL_HEIGHT));
            setMaximumSize(new Dimension(TAMAÑO_EXPANDIDO_WIDTH, TAMAÑO_EXPANDIDO_HEIGHT));
            setMinimumSize(new Dimension(TAMAÑO_NORMAL_WIDTH, TAMAÑO_NORMAL_HEIGHT));

            setBorder(BorderFactory.createLineBorder(Color.BLACK, 2));
            setLayout(null);
            setCursor(new Cursor(Cursor.HAND_CURSOR));

            numLabel = new JLabel("#" + numero);
            numLabel.setFont(new Font("Segoe UI", Font.BOLD, 16));
            numLabel.setHorizontalAlignment(SwingConstants.CENTER);
            numLabel.setForeground(Color.BLACK);
            numLabel.setBounds(0, 8, TAMAÑO_NORMAL_WIDTH, 25);
            add(numLabel);

            vacioLabel = new JLabel("SIN FIGURITA");
            vacioLabel.setFont(new Font("Segoe UI", Font.BOLD, 11));
            vacioLabel.setHorizontalAlignment(SwingConstants.CENTER);
            vacioLabel.setForeground(new Color(120, 120, 120));
            vacioLabel.setBounds(0, 130, TAMAÑO_NORMAL_WIDTH, 25);
            add(vacioLabel);
        }

        private void initAnimaciones() {
            hoverTimer = new Timer(12, e -> {
                if (hover && !seleccionado) {
                    if (animacionWidth < TAMAÑO_EXPANDIDO_WIDTH || animacionHeight < TAMAÑO_EXPANDIDO_HEIGHT) {
                        animacionWidth = Math.min(TAMAÑO_EXPANDIDO_WIDTH, animacionWidth + PASO_ANIMACION);
                        animacionHeight = Math.min(TAMAÑO_EXPANDIDO_HEIGHT, animacionHeight + PASO_ANIMACION);
                        actualizarAnimacion();
                    } else {
                        hoverTimer.stop();
                    }
                } else if (!hover && !seleccionado) {
                    if (animacionWidth > TAMAÑO_NORMAL_WIDTH || animacionHeight > TAMAÑO_NORMAL_HEIGHT) {
                        animacionWidth = Math.max(TAMAÑO_NORMAL_WIDTH, animacionWidth - PASO_ANIMACION);
                        animacionHeight = Math.max(TAMAÑO_NORMAL_HEIGHT, animacionHeight - PASO_ANIMACION);
                        actualizarAnimacion();
                    } else {
                        hoverTimer.stop();
                    }
                }
            });

            clickTimer = new Timer(10, e -> {
                if (seleccionado) {
                    if (animacionWidth < TAMAÑO_EXPANDIDO_WIDTH + 10 || animacionHeight < TAMAÑO_EXPANDIDO_HEIGHT + 10) {
                        animacionWidth = Math.min(TAMAÑO_EXPANDIDO_WIDTH + 10, animacionWidth + PASO_ANIMACION + 2);
                        animacionHeight = Math.min(TAMAÑO_EXPANDIDO_HEIGHT + 10, animacionHeight + PASO_ANIMACION + 2);
                        actualizarAnimacion();
                    } else {
                        clickTimer.stop();
                    }
                } else {
                    if (animacionWidth > (hover ? TAMAÑO_EXPANDIDO_WIDTH : TAMAÑO_NORMAL_WIDTH) ||
                        animacionHeight > (hover ? TAMAÑO_EXPANDIDO_HEIGHT : TAMAÑO_NORMAL_HEIGHT)) {
                        int targetW = hover ? TAMAÑO_EXPANDIDO_WIDTH : TAMAÑO_NORMAL_WIDTH;
                        int targetH = hover ? TAMAÑO_EXPANDIDO_HEIGHT : TAMAÑO_NORMAL_HEIGHT;
                        animacionWidth = Math.max(targetW, animacionWidth - PASO_ANIMACION - 2);
                        animacionHeight = Math.max(targetH, animacionHeight - PASO_ANIMACION - 2);
                        actualizarAnimacion();
                    } else {
                        clickTimer.stop();
                    }
                }
            });

            addMouseListener(new MouseAdapter() {
                @Override
                public void mouseEntered(MouseEvent e) {
                    hover = true;
                    if (!seleccionado) {
                        setBorder(BorderFactory.createLineBorder(Color.BLACK, 3));

                        hoverTimer.start();
                    }
                }

                @Override
                public void mouseExited(MouseEvent e) {
                    hover = false;
                    if (!seleccionado) {
                        setBorder(BorderFactory.createLineBorder(Color.BLACK, 2));

                        hoverTimer.start();
                    }
                }

                @Override
                public void mouseClicked(MouseEvent e) {
                    if (seleccionado) {
                        seleccionado = false;
                        setBorder(BorderFactory.createLineBorder(Color.BLACK, 2));
                        slotSeleccionado = null;

                        clickTimer.start();
                    } else {
                        if (slotSeleccionado != null && slotSeleccionado != SlotPanel.this) {
                            slotSeleccionado.deseleccionar();
                        }
                        seleccionado = true;
                        slotSeleccionado = SlotPanel.this;
                        setBorder(BorderFactory.createLineBorder(Color.BLACK, 4));

                        clickTimer.start();
                    }
                }
            });
        }

        private void deseleccionar() {
            seleccionado = false;
            hover = false;
            setBorder(BorderFactory.createLineBorder(Color.BLACK, 2));

            clickTimer.start();
        }

        private void actualizarAnimacion() {
            setPreferredSize(new Dimension(animacionWidth, animacionHeight));
            if (numLabel != null) {
                numLabel.setBounds(0, 8, animacionWidth, 25);
                numLabel.setFont(new Font("Segoe UI", Font.BOLD, seleccionado ? 18 : 16));
            }
            if (vacioLabel != null) {
                vacioLabel.setBounds(0, animacionHeight / 2 - 12, animacionWidth, 25);
                vacioLabel.setFont(new Font("Segoe UI", Font.BOLD, seleccionado ? 12 : 11));
            }
            revalidate();
            repaint();
        }
    }

